const PivotTableDashboard = () => {
  const [value, setValue] = useState(0);
  const [startDate, setStartDate] = useState('');
  const [endDate, setEndDate] = useState('');
  const [configuredBy, setConfiguredBy] = useState('');
  const [filteredData, setFilteredData] = useState(data);
  const [lineChartOptions, setLineChartOptions] = useState({});
  const [pieChartOptions, setPieChartOptions] = useState({});

  useEffect(() => {
    filterData(); // Re-filter data whenever start or end date changes
  }, [startDate, endDate, configuredBy]);

  useEffect(() => {
    updateCharts(filteredData);
  }, [filteredData]);

  const updateCharts = (filteredData) => {
    const monthCounts = {};

    filteredData.forEach(item => {
      const date = new Date(item['Start Date']);
      const monthYear = date.toLocaleString('default', { month: 'long', year: 'numeric' });

      monthCounts[monthYear] = (monthCounts[monthYear] || 0) + 1;
    });

    const months = Object.keys(monthCounts);
    const counts = Object.values(monthCounts);

    setLineChartOptions({
      title: {
        text: 'Event Line Chart (Monthly)',
      },
      xAxis: {
        categories: months,
      },
      series: [
        {
          name: 'Total Events',
          data: counts,
          color: '#36A2EB',
        },
      ],
    });

    const configuredByCounts = filteredData.reduce((acc, item) => {
      acc[item['Configured By']] = (acc[item['Configured By']] || 0) + 1;
      return acc;
    }, {});

    const pieData = Object.keys(configuredByCounts).map(name => ({
      name,
      y: configuredByCounts[name],
      color: '#36A2EB',
    }));

    setPieChartOptions({
      chart: {
        type: 'pie',
      },
      title: {
        text: 'Event Distribution',
      },
      series: [
        {
          name: 'Events',
          colorByPoint: true,
          data: pieData,
        },
      ],
    });
  };

  const filterData = () => {
    const filtered = data.filter((item) => {
      const itemDate = new Date(item['Start Date']);
      const start = new Date(startDate);
      const end = new Date(endDate);
      const dateInRange = itemDate >= start && itemDate <= end;

      const configuredByMatches = configuredBy ? item['Configured By'] === configuredBy : true;

      return (startDate && endDate ? dateInRange : true) && configuredByMatches;
    });
    setFilteredData(filtered);
  };

  const handleChange = (event, newValue) => {
    setValue(newValue);
    };
    const [pivotrows, setPivotRows] = useState(['Configured By'])
    const [pivotcols, setPivotCols] = useState(['Configure Date'])
     const [aggregatorName,setAggregatorName]=useState('Count')
    const [rendererName,setRendererName]=useState('Table')
          
  return (
    <Container>
      <Tabs value={value} onChange={handleChange} aria-label="basic tabs example">
        <Tab label="RFQ Grid" />
        <Tab label="RFQ Analytics" />
        <Tab label="RFQ Pivot Analytics" />
      </Tabs>
          <Box sx={{ padding: 2 }}>
              {value == 0 && <>
                   <ManageRFQ />
                 </>}
        {value === 1 && (
          <>
            <DateFilter>
              <label htmlFor="start-date">Start Date:</label>
              <input type="date" id="start-date" value={startDate} onChange={(e) => setStartDate(e.target.value)} />
              <label htmlFor="end-date">End Date:</label>
              <input type="date" id="end-date" value={endDate} onChange={(e) => setEndDate(e.target.value)} />
              <label htmlFor="configured-by">Configured By:</label>
              <select id="configured-by" value={configuredBy} onChange={(e) => setConfiguredBy(e.target.value)}>
                <option value="">All</option>
                {[...new Set(data.map(item => item['Configured By']))].map((name) => (
                  <option key={name} value={name}>{name}</option>
                ))}
              </select>
            </DateFilter>

            <ChartContainer>
              <ChartWrapper>
                <HighchartsReact highcharts={Highcharts} options={lineChartOptions} />
              </ChartWrapper>
              <ChartWrapper>
                <HighchartsReact highcharts={Highcharts} options={pieChartOptions} />
              </ChartWrapper>
            </ChartContainer>

            <TableContainer>
              <StyledTable>
                <thead>
                  <tr>
                    <th>Event ID</th>
                    <th>RFQ Subject</th>
                    <th>Configured By</th>
                    <th>Start Date</th>
                    <th>RFQ Deadline</th>
                  </tr>
                </thead>
                <tbody>
                  {filteredData.map((item) => (
                    <tr key={item['Event ID']}>
                      <td>{item['Event ID']}</td>
                      <td>{item['RFQ Subject']}</td>
                      <td>{item['Configured By']}</td>
                      <td>{item['Start Date']}</td>
                      <td>{item['RFQ Deadline']}</td>
                    </tr>
                  ))}
                </tbody>
              </StyledTable>
            </TableContainer>
          </>
        )}
              {value === 2 && (
                  <PivotTableComponent startDate={startDate} endDate={endDate} configuredBy={configuredBy} />
          
        )}
      </Box>
    </Container>
  );
};

export default PivotTableDashboard;


